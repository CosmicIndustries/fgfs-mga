#!/usr/bin/env python3
"""Put the Aquila walker on every fleet plane.

usage: gen_walker.py EXITS_FILE BACKUP_DIR [--dry-run | --undo] [name ...]

For each plane this writes aquila-walker.xml next to the file at the bottom of
the plane's include chain and points that file's <PropertyList include=...> at it.
aquila-walker.xml is FlightGear's walker-include.xml with:
  - the Aquila flight suit (outfit 5) as the default outfit,
  - an exit beside the plane's door (from EXITS_FILE, made by exits.py),
  - no walker key that the plane already binds itself (an include merges key
    bindings by index, which would put walker conditions on the plane's own keys),
  - w / W driving the walker only in the walk views, so they keep warping time
    in the cockpit.
Every file it changes is copied to BACKUP_DIR first (once); --undo copies them back."""
import os, re, sys, shutil
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from survey import FLEET, find, load_chain, FGROOT

STOCK_INC = "Aircraft/Generic/Human/Include/walker-include.xml"
WALKVIEW = ("<condition><or><equals><property>sim/current-view/name</property><value>Walk View</value></equals>"
            "<equals><property>sim/current-view/name</property><value>Walker Orbit View</value></equals></or></condition>")
NOTWALK = ("<condition><and><not-equals><property>sim/current-view/name</property><value>Walk View</value></not-equals>"
           "<not-equals><property>sim/current-view/name</property><value>Walker Orbit View</value></not-equals></and></condition>")


def keys_bound_at_zero(text):
    out = set()
    for m in re.finditer(r'<key n="(\d+)"[^>]*>(.*?)</key>', text, re.S):
        body = re.sub(r"<mod-[a-z]+>.*?</mod-[a-z]+>", "", m.group(2), flags=re.S)
        if re.search(r'<binding(\s+n="0")?\s*>', body):
            out.add(m.group(1))
    return out


def warp_key(n, name, desc, step):
    return f'''		<key n="{n}">
			<name>{name}</name>
			<desc>{desc}</desc>
			<repeatable>false</repeatable>
			<binding n="0">
				{WALKVIEW}
				<command>property-assign</command>
				<property>sim/walker/key-triggers/forward</property>
				<value>1</value>
			</binding>
			<binding n="1">
				<command>property-assign</command>
				<property>sim/walker/key-triggers/speed</property>
				<property>sim/walker/speed-mps</property>
			</binding>
{"" if step > 0 else """			<binding n="2">
				<command>property-multiply</command>
				<property>sim/walker/key-triggers/speed</property>
				<factor>5.0</factor>
			</binding>
"""}			<binding n="3">
				{NOTWALK}
				<command>property-adjust</command>
				<property>/sim/time/warp</property>
				<step type="int">{step}</step>
			</binding>
			<mod-up>
				<binding n="0">
					<command>property-assign</command>
					<property>sim/walker/key-triggers/forward</property>
					<value>0</value>
				</binding>
				<binding n="1">
					<command>property-assign</command>
					<property>sim/walker/key-triggers/speed</property>
					<property>sim/walker/speed-mps</property>
				</binding>
			</mod-up>
		</key>'''


def make_include(stock, drop_keys, exit_xy):
    t = re.sub(r"<!--.*?-->", "", stock, flags=re.S)
    t = t.replace("<PropertyList>", "<!-- Generated by fgfs-mga aircraft/aquila-walker/gen_walker.py from FlightGear's\n"
                  "     " + STOCK_INC + ": the walker in the Aquila Flight Program flight suit. -->\n<PropertyList>", 1)
    # default outfit: Aquila flight suit
    t, n = re.subn(r"(<walker>\s*<character>0</character>\s*<gender>0</gender>\s*)<outfit>0</outfit>",
                   r"\1<outfit>5</outfit>\n\t\t<theme-name>Waldo Aquila Flight Suit</theme-name>", t, count=1)
    assert n == 1, "outfit default not found"
    if exit_xy:
        t, n = re.subn(r"<default_exit>\s*</default_exit>",
                       f'<default_exit>\n\t\t\t\t\t<x-offset-m type="float">{exit_xy[0]:.2f}</x-offset-m>\n'
                       f'\t\t\t\t\t<y-offset-m type="float">{exit_xy[1]:.2f}</y-offset-m>\n\t\t\t\t</default_exit>', t, count=1)
        assert n == 1, "default_exit not found"
    for k in list(re.findall(r'<key n="(\d+)">', t)):
        blk = re.search(r'[ \t]*<key n="%s">.*?</key>' % k, t, re.S)
        if k == "119" and k in drop_keys:
            # the plane uses w itself; walking forward is too useful to lose, so the walker's
            # bindings sit at indices the plane doesn't use and only act in the walk views
            t = t[:blk.start()] + f'''		<key n="119">
			<binding n="10">
				{WALKVIEW}
				<command>property-assign</command>
				<property>sim/walker/key-triggers/forward</property>
				<value>1</value>
			</binding>
			<binding n="11">
				<command>property-assign</command>
				<property>sim/walker/key-triggers/speed</property>
				<property>sim/walker/speed-mps</property>
			</binding>
			<mod-up>
				<binding n="10">
					<command>property-assign</command>
					<property>sim/walker/key-triggers/forward</property>
					<value>0</value>
				</binding>
			</mod-up>
		</key>''' + t[blk.end():]
        elif k in drop_keys:
            t = t[:blk.start()] + t[blk.end():]
        elif k == "119":
            t = t[:blk.start()] + warp_key(119, "w", "Walk forward (walk views); increase warp (other views)", 60) + t[blk.end():]
        elif k == "87":
            t = t[:blk.start()] + warp_key(87, "W", "Run forward (walk views); decrease warp (other views)", -60) + t[blk.end():]
    t = re.sub(r"\n\s*\n\s*\n+", "\n\n", t)
    return t


def plan():
    out = []
    for name, folder, ident in FLEET:
        d, f = find(folder, ident)
        if not f:
            out.append((name, None, None, None, "not installed")); continue
        chain = load_chain(f, d)
        own = [c for c, _ in chain if "Generic/Human" not in c]
        base = None
        for c, inc in chain:
            if inc == STOCK_INC or inc == "aquila-walker.xml" or inc is None:
                base = c; break
        # follow element-level includes too (<input include="keys.xml"/>, <menubar include=...>)
        seen, todo = [], list(own)
        while todo:
            c = todo.pop()
            if c in seen or not os.path.exists(c) or "Generic/Human" in c or "aquila-walker.xml" in c:
                continue
            seen.append(c)
            for inc in re.findall(r'include\s*=\s*"([^"]+)"', open(c, errors="replace").read()):
                for cand in (os.path.join(os.path.dirname(c), inc), os.path.join(d, inc), os.path.join(FGROOT, inc)):
                    if os.path.exists(cand):
                        todo.append(cand); break
        text = "".join(open(c, errors="replace").read() for c in seen)
        out.append((name, d, base, keys_bound_at_zero(text), "ok"))
    return out


def main():
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    exits_file, backup = args[0], args[1]
    only = set(args[2:])
    dry = "--dry-run" in sys.argv
    undo = "--undo" in sys.argv
    exits = {}
    for ln in open(exits_file):
        m = re.match(r"(\S+)\s.*exit x=([-0-9.]+) y=([-0-9.]+)", ln)
        if m:
            exits[m.group(1)] = (float(m.group(2)), float(m.group(3)))
    stock = open(os.path.join(FGROOT, STOCK_INC)).read()
    home = os.path.expanduser("~")
    for name, d, base, keys, status in plan():
        if only and name not in only:
            continue
        if status != "ok":
            print(f"{name}: {status}"); continue
        gen = os.path.join(os.path.dirname(base), "aquila-walker.xml")
        bk = os.path.join(backup, "aircraft", os.path.relpath(base, home).replace("/", "__"))
        if undo:
            if os.path.exists(bk):
                shutil.copy2(bk, base); print(f"{name}: restored {base}")
            if os.path.exists(gen):
                os.remove(gen); print(f"{name}: removed {gen}")
            continue
        walker_keys = set(re.findall(r'<key n="(\d+)">', re.sub(r"<!--.*?-->", "", stock, flags=re.S)))
        drop = keys & walker_keys
        ex = exits.get(name)
        txt = open(base, errors="replace").read()
        own_exit = "default_exit" in txt
        print(f"{name}: base={os.path.relpath(base, home)} drop_keys={sorted(drop, key=int)} "
              f"exit={'own' if own_exit else ex}")
        if dry:
            continue
        if ex is None and not own_exit:
            print(f"   {name}: no exit found, skipped"); continue
        os.makedirs(os.path.dirname(bk), exist_ok=True)
        if not os.path.exists(bk):
            shutil.copy2(base, bk)
        open(gen, "w").write(make_include(stock, drop, ex))
        # the first <PropertyList> outside a comment (the 182S keeps a commented-out one above it)
        nocom = re.sub(r"<!--.*?-->", lambda c: " " * len(c.group(0)), txt, flags=re.S)
        m = re.search(r"<PropertyList([^>]*)>", nocom)
        attrs = m.group(1)
        if "include=" in attrs:
            new = re.sub(r'include\s*=\s*"[^"]*"', 'include="aquila-walker.xml"', attrs)
        else:
            new = attrs + ' include="aquila-walker.xml"'
        txt = txt[:m.start(1)] + new + txt[m.end(1):]
        open(base, "w").write(txt)


if __name__ == "__main__":
    main()
